/**
 * Write the preview's `custom_fields` from the demo board.
 *
 * `trmnlp` renders whatever `.trmnlp.yml` says, and TRMNL has no API to read
 * a user's stored settings back — `trmnlp` only pushes. So the local preview
 * can never discover what a given panel is actually configured to show.
 *
 * What it *can* do is render a board both sides agree on. The demo board is
 * that board: it is what an unconfigured install displays, it exercises all
 * five transit types across six slots, and it lives in `settings.ts` as the
 * single definition — so generating the YAML from it means the preview
 * cannot drift from the thing it claims to preview. Hand-copied values would
 * drift the first time a demo station changed, which is exactly how the
 * preview came to be showing a board the server had not served for days.
 *
 * To preview your own panel instead, replace the generated block by hand and
 * do not re-run this. The values are what the picker stores — see
 * `parseCard` for the grammar.
 *
 *   npm run preview:sync
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { DEMO_CARDS } from "../src/settings.ts";

const here = dirname(fileURLToPath(import.meta.url));
const CONFIG = resolve(here, "../plugin/.trmnlp.yml");

const MARKER_START = "  # BEGIN generated by npm run preview:sync";
const MARKER_END = "  # END generated by npm run preview:sync";

/** The station value the picker would have stored for this card. */
function stationValue(card) {
  // The picker writes the transit type on the front and joins a station's
  // several platform IDs with "+". `parseCard` reads exactly this shape.
  const ids = card.stopIds.join("+");
  const routes = card.routes?.length ? `!${card.routes.join(",")}` : "";
  return `${card.transitType}:${ids}${routes}`;
}

const lines = [MARKER_START];
for (let slot = 1; slot <= 6; slot++) {
  const card = DEMO_CARDS.find((c) => c.slot === slot);
  lines.push(`  card${slot}_visible: ${card ? "true" : "false"}`);
  lines.push(`  card${slot}_station: "${card ? stationValue(card) : ""}"`);
  lines.push(`  card${slot}_walk: ${card?.walkTime ?? 5}`);
  lines.push(`  card${slot}_title: "${card?.title ?? ""}"`);
  if (slot < 6) lines.push("");
}
lines.push(MARKER_END);

const config = readFileSync(CONFIG, "utf8");
const start = config.indexOf(MARKER_START);
const end = config.indexOf(MARKER_END);

if (start === -1 || end === -1) {
  console.error(
    `No generated block in ${CONFIG}.\n` +
      `Add these markers around the card fields under custom_fields:\n` +
      `${MARKER_START}\n  ...\n${MARKER_END}`
  );
  process.exit(1);
}

const next =
  config.slice(0, start) + lines.join("\n") + config.slice(end + MARKER_END.length);

writeFileSync(CONFIG, next, "utf8");
console.log(
  `wrote ${DEMO_CARDS.length} demo card(s) into plugin/.trmnlp.yml\n` +
    `run \`trmnlp build\` to render them`
);
